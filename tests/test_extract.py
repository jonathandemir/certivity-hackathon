SPEC = """# spec: Rear Lamp

## Product Type

Rear lamp  — exterior lighting & signalling module

## Function

- Rear position signalling (presence/visibility)
- Braking indication (stop lamp)

## Main Parts

- Rear position lamp
- Stop lamp
- Retro-reflector
- Housing

## Materials

| Component | Typical material(s) |
| Light source | LED modules on PCB |
"""


def _p(label, title="", text="x shall y", headings=()):
    number = label.split()[-1]
    return Paragraph(label, number, 1, 1, (title + " " + text).strip(), title, tuple(headings))


def test_spec_terms_from_parts_and_functions_only():
    terms = spec_terms(SPEC)
    assert ("stop", "lamp") in terms and ("retro", "reflector") in terms and ("rear", "position", "lamp") in terms
    assert ("housing",) in terms  # Einzelwort als ganzer Aufzählungspunkt unter Main Parts
    assert ("presence",) not in terms and ("visibility",) not in terms  # Einzelwörter aus Klammern nicht
    assert ("light", "source") not in terms  # Materialtabelle zählt nicht


def test_matching_term_respects_position_words():
    terms, words = spec_terms(SPEC), set(_words(SPEC))
    assert _matching_term("Rear retro-reflector, non-triangular", terms, words) == ("retro", "reflector")
    assert _matching_term("Front retro-reflector, non-triangular", terms, words) is None
    assert _matching_term("Stop lamps (S1, S2, S3, S4, MS)", terms, words) == ("stop", "lamp")
    assert _matching_term("Rear fog lamp", terms, words) is None


def test_parts_drops_only_unmatched_members_of_an_enumeration():
    paras = (_p("6", "Individual specifications"), _p("6.1", "Main-beam headlamp"), _p("6.1.1"),
             _p("6.2", "Front fog lamp"), _p("6.2.1"), _p("6.3", "Stop lamp"), _p("6.3.1"),
             _p("6.4", "Rear fog lamp"), _p("6.4.1"), _p("6.5", "General"), _p("6.5.1"))
    keep = dict(zip([p.label for p in paras], relevant(paras, ("parts",), SPEC)))
    assert keep["6.3.1"] and keep["6.5.1"] and keep["6"]
    assert not keep["6.1.1"] and not keep["6.2.1"] and not keep["6.4.1"]
    # ohne Spezifikation oder ohne Treffer: nichts verwerfen
    assert all(relevant(paras, ("parts",), ""))
    assert all(relevant(paras[:3], ("parts",), SPEC))


def test_admin_cop_esa_rules():
    paras = (_p("3", "Administrative provisions"), _p("3.1", "Application for approval"), _p("3.1.1"),
             _p("3.3", "Approval marking and other markings"), _p("3.3.1"),
             _p("6", "Conformity of production"), _p("6.1.1"),
             _p("6.1.3", text="The measured values shall not deviate unfavourably by more than 20 per cent."),
             _p("7", "Specifications"), _p("7.1", "Specifications concerning radiation from vehicles"), _p("7.1.1"),
             _p("7.2", "Specifications concerning interference generated by ESAs"), _p("7.2.1"))
    for p in paras:  # headings wie der Parser sie setzt
        parents = [q.title for q in paras if q.title and p.number.startswith(q.number + ".")]
        p.headings = tuple(parents)
    keep = dict(zip([p.label for p in paras], relevant(paras, ("admin", "cop", "esa"), SPEC)))
    assert not keep["3.1.1"] and keep["3.3.1"]
    assert not keep["6.1.1"] and keep["6.1.3"]  # Fertigungstoleranz bleibt
    assert not keep["7.1.1"] and keep["7.2.1"]
    with pytest.raises(ValueError):
        relevant(paras, ("bogus",), SPEC)


@needs_package
def test_filters_keep_every_gold_paragraph_of_b0(dev_expected):
    """Auf dem Dev-Fall darf kein Filter einen Gold-Absatz verlieren, den B0 findet (Stand der Messung E004)."""
    case = load_case(DEV_CASE)
    regs = select_regulations(case, ["UN R148", "UN R48", "UN R150", "UN R10"])
    gold = {(r["source"]["regulation"], r["source"]["paragraph"].split(". Table")[0].rstrip(".")) for r in dev_expected}
    b0 = {(r.regulation, r.paragraph) for r in extract_requirements(regs)} & gold
    filtered = extract_requirements(regs, case.spec_text, ("admin", "cop", "parts", "esa"))
    assert b0 - {(r.regulation, r.paragraph) for r in filtered} == set()
    assert len(filtered) < 0.6 * len(extract_requirements(regs))


